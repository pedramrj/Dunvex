export type Key = keyof Dict;

interface Ctx {
  lang: Lang;
  t: (k: Key) => string;
  setLang: (l: Lang) => void;
  n: (v: number, digits?: number) => string;
}

const I18n = createContext<Ctx>(null as any);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      return (localStorage.getItem("dvx-lang") as Lang) || "fa";
    } catch {
      return "fa";
    }
  });
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "fa" ? "rtl" : "ltr";
  }, [lang]);
  const value = useMemo<Ctx>(() => {
    const dict = lang === "fa" ? fa : en;
    const nf = new Map<number, Intl.NumberFormat>();
    return {
      lang,
      t: (k) => dict[k] ?? k,
      setLang: (l) => {
        try {
          localStorage.setItem("dvx-lang", l);
        } catch {}
        setLangState(l);
      },
      n: (v, digits = 0) => {
        if (!nf.has(digits)) nf.set(digits, new Intl.NumberFormat(lang === "fa" ? "fa-IR" : "en-US", { maximumFractionDigits: digits, minimumFractionDigits: 0 }));
        return nf.get(digits)!.format(v);
      },
    };
  }, [lang]);
  return <I18n.Provider value={value}>{children}</I18n.Provider>;
}

export const useI18n = () => useContext(I18n);
