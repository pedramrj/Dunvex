# ================================================================= step log
STEP_N=0
STEP_T=1
step_head() { # [01/07] ⟩ TAG      label .........
  local tag=$1 label=$2 dots
  dots=$((36 - ${#label})); [ $dots -lt 2 ] && dots=2
  printf '  %s[%02d/%02d]%s %s%s%s %s%-7s%s %s%s %s%s%s' "$DIM" "$STEP_N" "$STEP_T" "$R" "$C2" "$AR" "$R" \
    "$M$BD" "$tag" "$R" "$W" "$label" "$DIM" "$(printf '%*s' "$dots" '' | tr ' ' '.')" "$R"
}
step_ok() { printf '\r\e[K%s %s%s%s %s%s%s\n' "$(step_head "$1" "$2")" "$G" "$OK" "$R" "$GR" "${3:-}" "$R"; }
step_fail() {
  printf '\r\e[K%s %s%s%s\n' "$(step_head "$1" "$2")" "$RED" "$NO" "$R"
  printf '%s' "$DIM"; tail -n 15 "$LOG" | sed 's/^/      │ /'; printf '%s' "$R"
  die "${3:-step failed}"
}

# task TAG "label" command...   runs the command with a spinner; output goes to the log
task() {
  local tag=$1 label=$2 pid i=0 t0=$SECONDS
  shift 2
  STEP_N=$((STEP_N + 1))
  if [ "$FANCY" != 1 ]; then
    printf '  [%02d/%02d] %s %s ... ' "$STEP_N" "$STEP_T" "$tag" "$label"
    if "$@" >>"$LOG" 2>&1; then echo "ok"; return 0; fi
    echo "FAIL"; tail -n 15 "$LOG"; die "$label failed"
  fi
  cursor_off
  "$@" >>"$LOG" 2>&1 &
  pid=$!
  while kill -0 "$pid" 2>/dev/null; do
    printf '\r%s %s%s%s %s%ss%s' "$(step_head "$tag" "$label")" "$C1" "${SP:i++%${#SP}:1}" "$R" "$DIM" "$((SECONDS - t0))" "$R"
    sleep 0.08
  done
  cursor_on
  if wait "$pid"; then step_ok "$tag" "$label" "${TASK_NOTE:-$((SECONDS - t0))s}"; TASK_NOTE=""
  else step_fail "$tag" "$label" "$label failed"; fi
}
TASK_NOTE=""

human() { awk -v b="$1" 'BEGIN{s="B KB MB GB";split(s,u," ");i=1;while(b>=1024&&i<4){b/=1024;i++};printf (i==1?"%d %s":"%.1f %s"),b,u[i]}'; }

download() { # download <url> <file> TAG "label": live bar with size and speed
  local url=$1 out=$2 tag=$3 label=$4 total size pid w=22 fill pct t0=$SECONDS bar speed el
  STEP_N=$((STEP_N + 1))
  total=$(curl -fsSIL --max-time 15 "$url" 2>/dev/null | tr -d '\r' | awk 'tolower($1)=="content-length:"{v=$2} END{print v+0}')
  if [ "$FANCY" != 1 ]; then
    printf '  [%02d/%02d] %s %s ... ' "$STEP_N" "$STEP_T" "$tag" "$label"
    curl -fsSL --retry 3 -o "$out" "$url" >>"$LOG" 2>&1 || { echo FAIL; die "download failed: $url"; }
    echo "ok"; return 0
  fi
  cursor_off
  curl -fsSL --retry 3 -o "$out" "$url" >>"$LOG" 2>&1 &
  pid=$!
  while kill -0 "$pid" 2>/dev/null; do
    size=$(stat -c %s "$out" 2>/dev/null || echo 0)
    el=$((SECONDS - t0)); [ $el -lt 1 ] && el=1
    speed=$((size / el))
    if [ "$total" -gt 0 ]; then
      fill=$((size * w / total)); pct=$((size * 100 / total))
      bar="$C1$(printf '%*s' "$fill" '' | sed 's/ /▰/g')$DIM$(printf '%*s' $((w - fill)) '' | sed 's/ /▱/g')$R"
      printf '\r\e[K%s %s %s%3d%%%s %s%s/s%s' "$(step_head "$tag" "$label")" "$bar" "$W" "$pct" "$R" "$GR" "$(human $speed)" "$R"
    else
      printf '\r\e[K%s %s%s%s' "$(step_head "$tag" "$label")" "$GR" "$(human "$size")" "$R"
    fi
    sleep 0.1
  done
  cursor_on
  if wait "$pid"; then step_ok "$tag" "$label" "$(human "$(stat -c %s "$out")") · $((SECONDS - t0))s"
  else step_fail "$tag" "$label" "download failed: $url"; fi
}

