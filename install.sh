  for l in "${lines[@]}"; do v=${l#*|}; [ $((${#v} + 17)) -gt $w ] && w=$((${#v} + 17)); done
  local p bar
  p=$(pad_to $((w + 4)))
  bar=$(printf '%*s' "$w" '' | sed 's/ /═/g')
  printf '%s%s╔%s╗%s\n' "$p" "$C3" "$bar" "$R"
  printf '%s%s║%s %s%s%s%*s%s║%s\n' "$p" "$C3" "$R" "$tc$BD" "$title" "$R" $((w - ${#title} - 1)) '' "$C3" "$R"
