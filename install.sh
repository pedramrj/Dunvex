show_word() { # the wordmark, decrypting out of noise
  local p noise='█▓▒░#%&@01' f i line out ch
  p=$(pad_to 52)
  for f in 6 5 4 3 2 1 0; do
    [ "$SKIP" = 1 ] && f=0
    for i in 0 1 2 3 4 5; do
      line=${WORD[i]}
      if [ "$f" -gt 0 ]; then
        out=""
        for ((k = 0; k < ${#line}; k++)); do
          ch=${line:k:1}
          if [ "$ch" != " " ] && ((RANDOM % 8 < f)); then ch=${noise:RANDOM%${#noise}:1}; fi
          out+=$ch
        done
      else out=$line; fi
      printf '%s%s%s%s\n' "$p" "${WGRAD[i]}" "$out" "$R"
    done
    [ "$f" -eq 0 ] && break
    nap 0.07
    printf '\e[6A'
  done
}

