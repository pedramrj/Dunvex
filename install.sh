host_line() {
  local os="Linux" mem cpu
  [ -r /etc/os-release ] && os=$(. /etc/os-release && echo "${PRETTY_NAME:-$NAME}")
  cpu=$(nproc 2>/dev/null || echo "?")
  mem=$(awk '/MemTotal/{printf "%.1f GB", $2/1048576}' /proc/meminfo 2>/dev/null || echo "?")
  echo "$os · $ARCH · $cpu vCPU · $mem"
}

need_deps() {
  NEED=()
  for c in curl tar; do command -v "$c" >/dev/null 2>&1 || NEED+=("$c"); done
  [ -e /etc/ssl/certs/ca-certificates.crt ] || [ -e /etc/pki/tls/certs/ca-bundle.crt ] || NEED+=(ca-certificates)
}
install_deps() {
  if command -v apt-get >/dev/null 2>&1; then
    apt-get update -qq && DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "${NEED[@]}"
  elif command -v dnf >/dev/null 2>&1; then dnf install -y -q "${NEED[@]}"
  elif command -v yum >/dev/null 2>&1; then yum install -y -q "${NEED[@]}"
  elif command -v pacman >/dev/null 2>&1; then pacman -Sy --noconfirm "${NEED[@]}"
  elif command -v apk >/dev/null 2>&1; then apk add --no-cache "${NEED[@]}" bash
  elif command -v zypper >/dev/null 2>&1; then zypper -q install -y "${NEED[@]}"
  else echo "Install ${NEED[*]} manually and run again." && return 1
  fi
}

gh_url() { # prefix github.com downloads with an optional mirror
  if [ -n "${DUNVEX_GITHUB_PROXY:-}" ]; then echo "${DUNVEX_GITHUB_PROXY%/}/$1"; else echo "$1"; fi
}

latest_tag() {
  if [ -n "${DUNVEX_BINARY:-}" ]; then "$DUNVEX_BINARY" version 2>/dev/null | awk '{print $2}'; return; fi
  if [ -n "${DUNVEX_VERSION:-}" ]; then echo "$DUNVEX_VERSION"; return; fi
  curl -fsSL --max-time 20 "https://api.github.com/repos/$REPO/releases/latest" | sed -n 's/.*"tag_name": *"\([^"]*\)".*/\1/p' | head -n1
}

TMP=""
fetch_binary() { # download, verify and install the dunvex binary for $TAG
  if [ -n "${DUNVEX_BINARY:-}" ]; then # offline: a binary already on this server
    [ -x "$DUNVEX_BINARY" ] || die "DUNVEX_BINARY is not an executable file: $DUNVEX_BINARY"
    STEP_N=$((STEP_N + 1)); step_ok FETCH "local binary" "$DUNVEX_BINARY"
    STEP_N=$((STEP_N + 1)); step_ok VERIFY "checksum" "skipped for a local file"
    task UNPACK "install binary" bash -c "install -m 0755 '$DUNVEX_BINARY' '$BIN.new' && mv -f '$BIN.new' '$BIN'"
    return
  fi
  TMP=$(mktemp -d)
  local name="dunvex-linux-$ARCH.tar.gz" url sum
  url=$(gh_url "https://github.com/$REPO/releases/download/$TAG/$name")
  download "$url" "$TMP/$name" FETCH "dunvex $TAG ($ARCH)"
  sum=$(gh_url "https://github.com/$REPO/releases/download/$TAG/$name.sha256")
  if curl -fsSL --max-time 20 -o "$TMP/$name.sha256" "$sum" 2>>"$LOG"; then
    TASK_NOTE="sha256 match" task VERIFY "checksum" bash -c "cd '$TMP' && sha256sum -c '$name.sha256'"
  else
    STEP_N=$((STEP_N + 1)); step_ok VERIFY "checksum" "no checksum published"
  fi
  task UNPACK "install binary" bash -c "tar -xzf '$TMP/$name' -C '$TMP' && install -m 0755 '$TMP/dunvex' '$BIN.new' && mv -f '$BIN.new' '$BIN'"
  rm -rf "$TMP"
}

write_unit() {
  cat >"$UNIT" <<EOF
[Unit]
