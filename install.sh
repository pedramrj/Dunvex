# ================================================================= terminal look
# Fancy mode needs a real terminal with 256 colours and a UTF-8 locale.
FANCY=0
if [ -t 1 ] && [ "${TERM:-dumb}" != "dumb" ] && [ -z "${NO_COLOR:-}" ] && [ -z "${DUNVEX_PLAIN:-}" ]; then
  for loc in C.UTF-8 C.utf8 en_US.UTF-8; do
    if LC_ALL=$loc bash -c 's="█"; [ ${#s} -eq 1 ]' 2>/dev/null; then export LC_ALL=$loc; break; fi
  done
  _s="█"
  if [ ${#_s} -eq 1 ] && [ "$(tput colors 2>/dev/null || echo 256)" -ge 256 ]; then FANCY=1; fi
fi
COLS=$( (tput cols || stty size 2>/dev/null | awk '{print $2}') 2>/dev/null || echo 80)
ROWS=$( (tput lines || stty size 2>/dev/null | awk '{print $1}') 2>/dev/null || echo 24)
[ "${COLS:-0}" -gt 20 ] 2>/dev/null || COLS=80
[ "${ROWS:-0}" -gt 10 ] 2>/dev/null || ROWS=24

if [ "$FANCY" = 1 ]; then
