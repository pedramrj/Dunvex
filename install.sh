[ "$(id -u)" -eq 0 ] || die "Run as root (sudo -i)."
command -v systemctl >/dev/null 2>&1 || die "systemd is required."
case "$(uname -m)" in
  x86_64 | amd64) ARCH=amd64 ;;
  aarch64 | arm64) ARCH=arm64 ;;
  *) die "Unsupported CPU: $(uname -m) (amd64 and arm64 are supported)" ;;
