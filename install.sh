matrix_rain() { # a short rain of hex glyphs falling down the screen
  local frames=$1 glyphs='0123456789ABCDEF<>/\\=+*#$' x y f buf ch
  local -a drop
  for ((x = 0; x < COLS; x += 2)); do drop[x]=$((-(RANDOM % ROWS))); done
  for ((f = 0; f < frames; f++)); do
    buf=""
    for ((x = 0; x < COLS; x += 2)); do
      y=${drop[x]}
      if ((y >= 0 && y < ROWS)); then
        ch=${glyphs:RANDOM%${#glyphs}:1}
        buf+=$'\e['"$((y + 1));$((x + 1))H${W}${ch}"
        ((y > 0)) && buf+=$'\e['"$y;$((x + 1))H${G}${glyphs:RANDOM%${#glyphs}:1}"
        ((y > 3)) && buf+=$'\e['"$((y - 2));$((x + 1))H${G2}${glyphs:RANDOM%${#glyphs}:1}"
        ((y > 6)) && buf+=$'\e['"$((y - 5));$((x + 1))H${G3}${glyphs:RANDOM%${#glyphs}:1}"
      fi
      ((y > 8)) && buf+=$'\e['"$((y - 8));$((x + 1))H "
      drop[x]=$((y + 1))
      ((y > ROWS + 9)) && drop[x]=$((-(RANDOM % 6)))
    done
    printf '%s' "$buf"
    key_pressed && break
    sleep 0.035
  done
  printf '%s\e[2J\e[H' "$R"
}

show_emblem() { # the logo, drawn line by line
  [ ${#EMBLEM[@]} -gt 0 ] || return 0
