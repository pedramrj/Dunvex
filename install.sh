cursor_off() { [ "$FANCY" = 1 ] && printf '\e[?25l' || true; }
cursor_on() { [ "$FANCY" = 1 ] && printf '\e[?25h%s' "$R" || true; }
cleanup() { cursor_on; rm -f "$LOG"; }
trap cleanup EXIT
trap 'cursor_on; echo; exit 130' INT TERM

SKIP=0
key_pressed() { # any key skips the animations
  [ "$SKIP" = 1 ] && return 0
  if [ -r /dev/tty ] && read -rsn1 -t 0.005 _ </dev/tty 2>/dev/null; then SKIP=1; return 0; fi
  return 1
}
nap() { [ "$SKIP" = 1 ] || sleep "$1"; }
pad_to() { # pad_to <visible width>: spaces that centre a block of that width
  local n=$(((COLS - $1) / 2)); [ $n -lt 0 ] && n=0; printf '%*s' "$n" ''
}

red() { printf '%s%s%s\n' "$RED" "$*" "$R"; }
green() { printf '%s%s%s\n' "$G" "$*" "$R"; }
die() { printf '\n  %s%s %s%s\n\n' "$RED" "$NO" "$*" "$R"; exit 1; }

