# ================================================================= commands
do_install() {
  if [ -x "$BIN" ] && [ -f "$HOME_DIR/data.db" ]; then
    do_update
    return
  fi
  banner full
  need_deps
  STEP_T=9
  [ ${#NEED[@]} -gt 0 ] && STEP_T=10
  STEP_N=1; step_ok PROBE "host" "$(host_line)"
  if [ ${#NEED[@]} -gt 0 ]; then TASK_NOTE="${NEED[*]}" task DEPS "system packages" install_deps; fi
  STEP_N=$((STEP_N + 1))
  TAG=$(latest_tag) || true
  [ -n "${TAG:-}" ] || step_fail RELEASE "latest release" "Could not read the latest release from GitHub."
  step_ok RELEASE "latest release" "$TAG"
  fetch_binary
  mkdir -p "$HOME_DIR"
  chmod 700 "$HOME_DIR"
  local args=()
  [ -n "${DUNVEX_PORT:-}" ] && args+=(--port "$DUNVEX_PORT")
  [ -n "${DUNVEX_USER:-}" ] && args+=(--user "$DUNVEX_USER")
  [ -n "${DUNVEX_PASS:-}" ] && args+=(--pass "$DUNVEX_PASS")
  export DUNVEX_HOME="$HOME_DIR"
  TASK_NOTE="xray + sing-box + geoip + starter protocols" task CORES "cores and admin" bash -c "umask 077; '$BIN' setup ${args[*]:-} > '$HOME_DIR/install-info.txt'"
  chmod 600 "$HOME_DIR/install-info.txt"
  TASK_NOTE="bbr · fq · fast open" task TUNE "network tuning" tune_network
  # open the panel's port and the starter protocols' ports (usually all 443: TCP for
  # the panel + Reality, UDP for Hysteria2), each once
  local panel_port fw_ports=() p
  panel_port=$(sed -n 's/.*Panel: *http[^:]*:\/\/[^:]*:\([0-9]*\)\/.*/\1/p' "$HOME_DIR/install-info.txt" | head -n1)
  for p in "${panel_port:-2096}" $(grep 'starter inbounds' "$HOME_DIR/install-info.txt" | grep -o '(port [0-9]*' | grep -o '[0-9]*$'); do
    [[ " ${fw_ports[*]} " == *" $p "* ]] || fw_ports+=("$p")
  done
  TASK_NOTE="$(IFS=' '; echo "${fw_ports[*]}") · tcp + udp" task SHIELD "firewall" open_firewall "${fw_ports[@]}"
  TASK_NOTE="systemd · dunvex.service" task SERVICE "start service" bash -c "$(declare -f write_unit wait_active); UNIT='$UNIT' HOME_DIR='$HOME_DIR' BIN='$BIN'; write_unit && systemctl enable --now dunvex && wait_active"
  finale_install
}

do_update() {
  MODE_LABEL="updating dunvex"
  local old
  old=$("$BIN" version 2>/dev/null | awk '{print $2}' || true)
  banner short
  STEP_T=6
  STEP_N=1; step_ok PROBE "host" "$(host_line)"
  need_deps
  [ ${#NEED[@]} -gt 0 ] && { STEP_T=7; TASK_NOTE="${NEED[*]}" task DEPS "system packages" install_deps; }
  STEP_N=$((STEP_N + 1))
  TAG=$(latest_tag) || true
  [ -n "${TAG:-}" ] || step_fail RELEASE "latest release" "Could not read the latest release from GitHub."
  step_ok RELEASE "latest release" "${old:-?} → $TAG"
  fetch_binary
  TASK_NOTE="restarted" task SERVICE "restart service" bash -c "$(declare -f write_unit wait_active); UNIT='$UNIT' HOME_DIR='$HOME_DIR' BIN='$BIN'; write_unit && systemctl restart dunvex && wait_active"
  printf '\n'
  printf '%s\n' "VERSION|${old:-?} → $TAG" "SERVICE|$(systemctl is-active dunvex)" | box "$G" "▓▓ UPDATED ▓▓  Dunvex $TAG"
  printf '\n  %s%s%s Updated to %s\n\n' "$G" "$OK" "$R" "$TAG"
}

do_uninstall() {
  MODE_LABEL="removing dunvex"
  banner short
  STEP_T=3
  task STOP "stop service" bash -c "systemctl disable --now dunvex >/dev/null 2>&1 || true; rm -f '$UNIT' /etc/sysctl.d/99-dunvex.conf; systemctl daemon-reload"
  local backup=""
  if [ -f "$HOME_DIR/data.db" ]; then
    backup="/root/dunvex-backup-$(date +%Y%m%d-%H%M%S).db"
    TASK_NOTE="$backup" task BACKUP "save database" cp -f "$HOME_DIR/data.db" "$backup"
  else STEP_N=$((STEP_N + 1)); step_ok BACKUP "save database" "nothing to save"; fi
  task WIPE "remove files" rm -rf "$HOME_DIR" "$BIN"
  printf '\n  %s%s%s Dunvex removed.%s\n\n' "$G" "$OK" "$R" "${backup:+ Database backed up to $backup}"
}

case "${1:-install}" in
  install) do_install ;;
  update) do_update ;;
  uninstall) do_uninstall ;;
  *) die "Usage: install.sh [install|update|uninstall]" ;;
esac
