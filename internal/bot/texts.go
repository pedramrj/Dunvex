func (b *Bot) t(key string) string {
	b.mu.Lock()
	lang := b.lang
	b.mu.Unlock()
	if m, ok := texts[lang]; ok {
		if v, ok := m[key]; ok {
			return v
		}
	}
	return texts["en"][key]
}

func (b *Bot) language() string {
	b.mu.Lock()
	defer b.mu.Unlock()
	return b.lang
}
