"""Writes internal/geoip/points.go: one map point per country code.

Input: Natural Earth 1:50m admin-0 countries as GeoJSON (public domain),
https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_50m_admin_0_countries.geojson

    python -I scripts/gen_country_points.py ne_50m_admin_0_countries.geojson
    gofmt -w internal/geoip/points.go

Natural Earth's LABEL_X / LABEL_Y is the point where a map would print the
country's name: inside the mainland, so France is in France and not between
it and French Guiana. When several features share a code (Australia and
Ashmore Is.), the most populous one wins.
"""
import json
import os
import sys

src = sys.argv[1]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
feats = json.load(open(src, encoding="utf-8"))["features"]

best = {}
for f in feats:
    p = f["properties"]
    cc = p.get("ISO_A2")
    if cc in (None, "", "-99"):
        cc = p.get("ISO_A2_EH")
    if cc in (None, "", "-99") or len(cc) != 2:
        continue
    pop = p.get("POP_EST") or 0
    if p.get("LABEL_Y") is None or p.get("LABEL_X") is None:
        continue
    if cc not in best or pop > best[cc][0]:
        best[cc] = (pop, round(p["LABEL_Y"], 2), round(p["LABEL_X"], 2), p.get("NAME", ""))

lines = [
    "// Code generated by scripts/gen_country_points.py; DO NOT EDIT.",
    "",
    "package geoip",
    "",
    "// points is where each country sits on the map (latitude, longitude): the",
    "// label point of Natural Earth 1:50m admin-0 countries (public domain).",
    "var points = map[string][2]float32{",
]
for cc in sorted(best):
    _, lat, lon, name = best[cc]
    lines.append(f'\t"{cc}": {{{lat}, {lon}}}, // {name}')
lines.append("}")
out = os.path.join(root, "internal", "geoip", "points.go")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines) + "\n")
print(len(best), "countries ->", out)
