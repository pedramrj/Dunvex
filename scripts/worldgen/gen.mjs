// Builds web/src/lib/world.ts: the world map's land and country borders as SVG
// paths in a Natural Earth projection, from Natural Earth (public domain) via
// world-atlas. Run once from a folder with the three packages installed:
//   npm i d3-geo topojson-client world-atlas && node gen.mjs > ../../web/src/lib/world.ts
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature, mesh } from "topojson-client";
import { geoNaturalEarth1, geoPath } from "d3-geo";
const require = createRequire(import.meta.url);
const file = (n) => readFileSync(require.resolve("world-atlas/" + n), "utf8");
const W = 1000, H = 500;
const topo = JSON.parse(file("countries-50m.json"));
const land = feature(topo, topo.objects.land);
// Antarctica holds no users: leave it out and let the rest fill the frame
land.features = land.features.map((f) => {
  if (f.geometry.type !== "MultiPolygon") return f;
  return { ...f, geometry: { ...f.geometry, coordinates: f.geometry.coordinates.filter((poly) => poly[0].some(([, lat]) => lat > -58)) } };
});
const proj = geoNaturalEarth1().fitExtent([[4, 4], [W - 4, H - 4]], land);
// drop points closer than 0.7 px to the previous one: the map is drawn at most ~6× zoom
function simplify(d) {
  return d.replace(/M[^MZ]*Z?/g, (ring) => {
    const closed = ring.endsWith("Z");
    const pts = ring.replace(/[MZ]/g, "").split("L").map((p) => p.split(",").map(Number));
    const out = [pts[0]];
    for (let i = 1; i < pts.length; i++) {
      const [x, y] = pts[i], [px, py] = out[out.length - 1];
      if (Math.hypot(x - px, y - py) >= 0.7 || i === pts.length - 1) out.push(pts[i]);
    }
    if (out.length < 3 && closed) return "";
    return "M" + out.map(([x, y]) => x.toFixed(1) + "," + y.toFixed(1)).join("L") + (closed ? "Z" : "");
  });
}
const path = geoPath(proj);
const LAND = simplify(path(land));
const BORDERS = simplify(path(mesh(topo, topo.objects.countries, (a, b) => a !== b)));
const [tx, ty] = proj.translate();
console.log(`// Generated by scripts/worldgen/gen.mjs from Natural Earth 1:50m (public domain) via world-atlas.
// The world without Antarctica in the Natural Earth projection, in a ${W}×${H} frame.
export const WORLD = { w: ${W}, h: ${H}, scale: ${proj.scale().toFixed(4)}, tx: ${tx.toFixed(4)}, ty: ${ty.toFixed(4)} };
export const LAND = ${JSON.stringify(LAND)};
export const BORDERS = ${JSON.stringify(BORDERS)};

/** Natural Earth projection (as d3-geo's geoNaturalEarth1) into the frame above. */
export function toXY(lon: number, lat: number): [number, number] {
  const l = (lon * Math.PI) / 180, p = (lat * Math.PI) / 180, p2 = p * p, p4 = p2 * p2;
  const x = l * (0.8707 - 0.131979 * p2 + p4 * (-0.013791 + p4 * (0.003971 * p2 - 0.001529 * p4)));
  const y = p * (1.007226 + p2 * (0.015085 + p4 * (-0.044475 + 0.028874 * p2 - 0.005916 * p4)));
  return [WORLD.tx + x * WORLD.scale, WORLD.ty - y * WORLD.scale];
}`);
